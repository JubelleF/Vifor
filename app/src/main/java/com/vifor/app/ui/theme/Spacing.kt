package com.vifor.app.ui.theme

import androidx.compose.ui.unit.dp

// One spacing scale for the whole app (4-pt grid). Layouts use Arrangement.spacedBy(Spacing.x)
// instead of hand-placed Spacers, so gaps stay consistent automatically.
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 16.dp
    val lg = 24.dp
    val xl = 32.dp
}